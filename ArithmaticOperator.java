class ArithmaticOperator {
    public static void main(String[] args) {
        //Addition
        int a=10;
        int b=20;
        int c=a+b;
        System.out.println(c);
        //Substraction
        int d=30;
        int e=36;
        int f=e-d;
        System.out.println(f);
        //Multiplication
        int g=80;
        int h=89;
        int j=g*h;
        System.out.println(j);
        //Division
        int k=20;
        int l=5;
        int m=k/l;
        System.out.println(m);
    }
    }

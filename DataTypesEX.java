class DataTypesEX {
    public static void main(String[] args) {
        int a=10;
        float b=10.5f;
        short c=5;
        double d=0.0000;
        char ch='A';
        System.out.println(a);
        System.out.println(b);
        System.out.println(c);
        System.out.println(d);
        System.out.println(ch);
    }
    }
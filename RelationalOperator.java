public class RelationalOperator {
    public static void main(String[] args) {
        int a=10;
        int b=20;
        System.out.println(a==b);

        System.out.println(a!=b);

        System.out.println(a>b);

        System.out.println(a<b);

        int num1=36;
        int num2=36;

        System.out.println(num1>=num2);

        System.out.println(num1<=num2);
    }
}

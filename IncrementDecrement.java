public class IncrementDecrement {
    public static void main(String[] args) {
        int a=10;
        a++;
        System.out.println(a);

        int b=10;
        ++b;
        System.out.println(b);

        int c=30;
        c--;
        System.out.println(c);
        int d=30;
        --d;
        System.out.println(d);
    }
}

public class AssigmentOperator {
    public static void main(String[] args) {
        int a=10;
        int b=a;
        System.out.println(b);

        // add and assign
        a +=2;
        System.out.println(a);
        //substract and assign
        b -=5;
        System.out.println(b);
        // Mul and assign
        int num=30;
         num *=2;
        System.out.println(num);
       // division and assign
        int num1=20;
        num1/=2;
        System.out.println(num1);
        // modulus and assign
        int num2=10;
        num2 %=2;
        System.out.println(num2);
    }
}
